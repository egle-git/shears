    Lumi_distr.clear();

    printf("standalone_LumiReWeighting Mode = %d\n", mode);

    char tmpName[50];
    char tmpNameMC[50];
    if( type.Contains("2016") )
        snprintf(tmpNameMC, 50, "%s", "2016"); // MC PU is same for both preAPV and postAPV samples
